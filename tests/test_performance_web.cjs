const assert=require('node:assert/strict');
const vm=require('node:vm');
const fs=require('node:fs');
const code=fs.readFileSync('web/performance.js','utf8');
function host(query=''){
  const listeners={},elements=[],frames=[];
  const element=()=>({style:{},children:[],hidden:false,open:false,appendChild(x){this.children.push(x);},addEventListener(type,fn){this[type]=fn;},showModal(){this.open=true;},close(){this.open=false;},click(){}});
  const gl={VERSION:1,RENDERER:2,VENDOR:3,drawingBufferWidth:1266,drawingBufferHeight:585,getParameter:x=>'observed-'+x,getExtension:()=>null};
  const canvas={...element(),width:1266,height:585,getContext:()=>gl};
  const document={visibilityState:'visible',body:element(),getElementById:()=>canvas,createElement:()=>{const x=element();elements.push(x);return x;},addEventListener:(n,f)=>{listeners[n]=f;}};
  let clock=100;
  const context={window:{},location:{search:query},URLSearchParams,navigator:{userAgent:'TEST, not a real browser measurement',platform:'mock',hardwareConcurrency:4},devicePixelRatio:3,innerWidth:844,innerHeight:390,document,requestAnimationFrame:fn=>frames.push(fn),performance:{now:()=>clock},fetch:()=>Promise.resolve({json:()=>Promise.resolve({commit:'fixture'})}),Blob,URL,setTimeout};
  vm.runInNewContext(code,context);
  return {api:context.window.__auraPerformance,context,elements,listeners,tick(now){clock=now;frames.shift()(now);}};
}
const off=host();assert.equal(off.api,undefined);assert.equal(off.elements.length,0);
const h=host('?perf=1&perf_device=explicit-test-label');
assert.equal(h.api.rasterRatio,null);assert.equal(h.api.snapshot().rafFps,null);
assert.equal(h.api.detailed,false);assert.equal(host('?perf=1&perf_detail=1').api.detailed,true);
assert.equal(h.api.snapshot().environment.deviceLabel,'explicit-test-label');
h.api.setMode('playing');assert.equal(h.elements[0].hidden,true);
h.tick(100);h.tick(116);h.tick(150);
let r=h.api.snapshot();assert.equal(r.frameTimeMs.samples,2);assert.equal(r.frameTimeMs.median,25);assert.equal(r.longFrames.over33_334,1);
assert.deepEqual(Array.from(r.environment.framebufferPixels),[1266,585]);
assert.equal(r.environment.dpr,3);assert.equal(r.environment.webglTimerExtension,false);
h.context.document.visibilityState='hidden';h.tick(500);
h.context.document.visibilityState='visible';h.listeners.visibilitychange();h.tick(1000);h.tick(1016);
assert.equal(h.api.snapshot().frameTimeMs.max,34,'Background wall time is excluded');
h.api.setMode('paused');assert.equal(h.elements[0].hidden,false);h.tick(2000);
h.api.setMode('playing');h.tick(3000);h.tick(3016);
h.listeners.pointermove({pointerType:'touch',isTrusted:true,timeStamp:3010});
h.listeners.pointermove({pointerType:'touch',isTrusted:false,timeStamp:3010});
assert.equal(h.api.snapshot().inputDispatchDelayMs.samples,1);
assert.equal(h.api.snapshot().inputDispatchDelayMs.median,6);
for(let i=0;i<3610;i++)h.tick(3032+i*16);
r=h.api.snapshot();assert.equal(r.rawRafMs.length,3600);assert.equal(r.frameTimeMs.median,16);assert.ok(r.totalRafFrames>3600);
for(const ratio of [1,1.25,1.5])assert.equal(host('?perf=1&perf_raster='+ratio).api.rasterRatio,ratio);
for(const ratio of ['0','2','NaN','-1'])assert.equal(host('?perf=1&perf_raster='+ratio).api.rasterRatio,null);
assert.equal(host('?perf_raster=1').api,undefined);
h.api.engineReport({sample_count:7});assert.equal(h.api.snapshot().engine.sample_count,7);
console.log('PASS: Opt-in browser recorder, bounded samples, visibility/pause, timing origin, framebuffer metadata and diagnostic-only raster choices');
